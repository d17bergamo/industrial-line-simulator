using LineSimulator.Models;

namespace LineSimulator.Core;

/// <summary>
/// Regola dell'utente (2026-11-10) per la fotocellula in ingresso al trasferitore e per quelle che comandano i fermi scomparenti:
/// distanza = Vmax² / (2 × accelerazione) + ritardo fotocellula (0,2 s) × Vmax, misurata dall'ingombro più a monte fra tutte le
/// combinazioni di posizione sul trasferitore (fermo finale, fermi scomparenti, double banking) e coda del pacco più lungo.
/// </summary>
public static class TransferEntryRule
{
    /// <summary>Ritardo di riferimento della fotocellula (s).</summary>
    public const double PhotocellDelayS = 0.2;

    /// <summary>Velocità massima e accelerazione della via davanti al trasferitore (o di tutte le vie se non c'è).</summary>
    private static (double V, double A) Drive(LineProject p)
    {
        var m = LayoutRules.TransferModule(p);
        var secs = m != null ? new[] { m } : p.Sections.ToArray();
        if (secs.Length == 0) return (RollerSection.DefaultMaxSpeed, RollerSection.DefaultAccel);
        double v = secs.Max(s => Math.Max(s.MaxSpeed, s.HighSpeed));
        double a = secs.Min(s => Math.Min(s.Acceleration, s.Deceleration));
        return (v, a > 0 ? a : RollerSection.DefaultAccel);
    }

    /// <summary>Distanza della regola (mm): Vmax² / (2a) + 0,2 s × Vmax, arrotondata per eccesso a 100 mm (nessun minimo di 2 m).</summary>
    public static double RequiredDistanceMm(LineProject p) => FormulaDistanceMm(p);

    /// <summary>Arrotondamento della distanza della regola.</summary>
    public const double RoundingMm = 100;

    /// <summary>La formula Vmax² / (2a) + 0,2 s × Vmax in mm, arrotondata per eccesso a 100 mm.</summary>
    public static double FormulaDistanceMm(LineProject p)
    {
        var (v, a) = Drive(p);
        return Math.Ceiling(Math.Round((v * v / (2 * a) + PhotocellDelayS * v) * 1000, 6) / RoundingMm) * RoundingMm;
    }

    /// <summary>Distanza della fotocellula di intestatura dopo un fermo scomparente di coda.</summary>
    public const double TailPhotocellAfterStopMm = 100;
    /// <summary>Suffisso della fotocellula di intestatura di coda di un fermo scomparente.</summary>
    public const string TailKeySuffix = ":coda";
    private static string TailKey(string stopId) => stopId + TailKeySuffix;

    /// <summary>Punto più a monte occupato da un pacco fermo sul trasferitore, fra tutte le combinazioni (mm in linea).</summary>
    public static double UpstreamFootprintMm(LineProject p)
    {
        double trfStart = p.Transfer.LengthMm > 0 ? p.Transfer.PositionMm : p.Stopper.PositionMm;
        if (p.PackageTypes.Count == 0) return trfStart;
        double lmax = p.PackageTypes.Max(t => t.LengthMm), lmin = p.PackageTypes.Min(t => t.LengthMm);
        double limit = trfStart - p.Transfer.EffectiveMaxOverhangMm;          // oltre lo sbalzo massimo il pacco non si carica
        var tails = new List<double> { p.Stopper.PositionMm - lmax };        // testa sul fermo finale
        foreach (var s in p.IntermediateStops.Where(s => s.IsEnabled))
        {
            tails.Add(s.PositionMm - lmax);                                    // testa sul fermo scomparente
            tails.Add(s.PositionMm);                                           // coda sul fermo scomparente
        }
        if (BankingOptions.ForSimulation(p).Banking == AccumulationMode.DoubleBanking)
            tails.Add(Math.Max(limit, p.Stopper.PositionMm - lmin - p.Transfer.DoubleBankingGapMm - lmax));   // secondo pacco in double banking
        return Math.Min(trfStart, Math.Max(limit, tails.Min()));
    }

    /// <summary>Posizione della fotocellula in ingresso al trasferitore secondo la regola.</summary>
    public static double EntryPhotocellPositionMm(LineProject p) => Math.Round(UpstreamFootprintMm(p) - RequiredDistanceMm(p));

    // ------------------------------------------------------------ fermi scomparenti

    /// <summary>
    /// Ogni fermo scomparente ha una fotocellula a monte che lo comanda: quello all'estremità (di coda) usa la fotocellula in
    /// ingresso al trasferitore; quello a metà ne riceve una sua, alla distanza della regola. Restituisce le modifiche.
    /// </summary>
    public static List<string> EnsureStopPhotocells(LineProject p)
    {
        var done = new List<string>();
        var stops = p.IntermediateStops.Where(s => s.IsEnabled).ToList();
        // fotocellule automatiche di fermi che non ci sono più
        foreach (var pc in p.Photocells.Where(x => x.IsAutoGenerated && !string.IsNullOrEmpty(x.CommandsStopId)
                                                   && !stops.Any(s => (s.Id == x.CommandsStopId && s.Placement != DevicePlacement.End)
                                                                     || (TailKey(s.Id) == x.CommandsStopId && s.Placement == DevicePlacement.End))).ToList())
        {
            p.Photocells.Remove(pc);
            done.Add($"{pc.Id}: tolta (il suo fermo scomparente non c'è più o ha cambiato posizione)");
        }
        var entry = p.Photocells.FirstOrDefault(x => x.ActsAsTransferStop);
        foreach (var s in stops)
        {
            if (s.Placement == DevicePlacement.End)
            {
                if (entry != null && entry.CommandsStopId != s.Id)
                {
                    entry.CommandsStopId = s.Id;
                    done.Add($"{s.Id} (di coda) comandato dalla fotocellula in ingresso al trasferitore {entry.Id}");
                }
                // 100 mm dopo il fermo: ferma il pacco, fa sollevare il fermo e comanda l'arretramento per l'intestatura di coda
                double xt = Math.Round(s.PositionMm + TailPhotocellAfterStopMm);
                var tp = p.Photocells.FirstOrDefault(o => o.CommandsStopId == TailKey(s.Id));
                if (tp == null)
                {
                    tp = NewAutoPhotocell(p, $"Intestatura {s.Id}", xt, TailKey(s.Id));
                    done.Add($"{tp.Id}: fotocellula di intestatura 100 mm dopo il fermo di coda {s.Id} (arresto, sollevamento fermo, arretramento)");
                }
                else if (Math.Abs(tp.PositionMm - xt) > 0.5)
                {
                    tp.PositionMm = xt;
                    done.Add($"{tp.Id}: portata a {xt:0} mm (100 mm dopo il fermo di coda {s.Id})");
                }
                continue;
            }
            double x = Math.Round(s.PositionMm - RequiredDistanceMm(p));
            var pc = p.Photocells.FirstOrDefault(o => o.CommandsStopId == s.Id && !o.ActsAsTransferStop);
            if (pc == null)
            {
                pc = NewAutoPhotocell(p, $"Comando {s.Id}", x, s.Id);
                done.Add($"{pc.Id}: fotocellula a monte del fermo scomparente {s.Id} a {x:0} mm");
            }
            else if (Math.Abs(pc.PositionMm - x) > 0.5)
            {
                pc.PositionMm = x;
                done.Add($"{pc.Id}: portata a {x:0} mm (regola del fermo scomparente {s.Id})");
            }
        }
        return done;
    }

    private static PhotocellConfig NewAutoPhotocell(LineProject p, string name, double x, string commands)
    {
        string id = "FC1";
        for (int i = 1; p.Photocells.Any(o => o.Id == id); i++) id = $"FC{i}";
        var pc = new PhotocellConfig
        {
            Id = id, Name = name, PositionMm = x, IsAutoGenerated = true, CommandsStopId = commands,
            Purpose = PhotocellPurpose.Generic, Action = PhotocellAction.None, DetectionMode = PhotocellDetectionMode.Presence
        };
        p.Photocells.Add(pc);
        return pc;
    }
}
