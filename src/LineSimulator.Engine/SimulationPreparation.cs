using System.Globalization;
using System.Text.RegularExpressions;
using LineSimulator.Core;
using LineSimulator.Models;
using LineSimulator.Optimization;

namespace LineSimulator.Engine;

/// <summary>Esito della preparazione del ciclo: correzioni applicate al progetto ed errori che impediscono la simulazione.</summary>
public sealed class PreparationReport
{
    public List<string> Changes { get; } = new();
    public List<string> Errors { get; } = new();
    public bool Changed => Changes.Count > 0;
    public bool HasErrors => Errors.Count > 0;
}

/// <summary>
/// Preparazione del ciclo prima della simulazione, eseguita dal motore e dall'interfaccia (sul progetto dell'utente):
/// <list type="number">
/// <item>nomi delle macchine e dei dispositivi: identificativi vuoti, duplicati o non in ordine lungo la linea vengono
/// rinumerati con un progressivo (M1.., L1.., FC1.., FM1.., B1..) e tutti i riferimenti vengono aggiornati;</item>
/// <item>la stazione di legatura segue le legatrici: si abilita se almeno una legatrice è abilitata, la sua zona è quella
/// che contiene le legatrici (moduli uniti in una zona di comando se le legatrici stanno su più moduli);</item>
/// <item>fotocellule con zona comandata inesistente, stringifascio/compattatore fuori posto e sensori automatici
/// (arresto davanti al trasferitore, encoder e fotocellula di riferimento) vengono riallineati;</item>
/// <item>legatura obbligatoria: con almeno una legatrice abilitata ogni pacco deve essere legato; se un pacco non è legabile
/// con la disposizione attuale la simulazione non parte e viene spiegato il motivo. Solo con tutte le legatrici
/// disabilitate i pacchi vanno al trasferitore senza legatura.</item>
/// </list>
/// </summary>
public static class SimulationPreparation
{
    private static readonly CultureInfo Ci = CultureInfo.InvariantCulture;
    private const double Tol = 1.0;

    public static PreparationReport Prepare(LineProject p)
    {
        var r = new PreparationReport();
        if (p.Sections.Count == 0) return r;
        FixIds(p, r);
        FixStation(p, r);
        // Svincolo: stesso inverter della via di legatura solo se durante la legatura la testa del pacco deve entrarci
        r.Changes.AddRange(StrappingAreaRules.DecideReleaseInverters(p));
        FixReferences(p, r);
        FixClampPositions(p, r, force: false);
        if (BankingOptions.Normalize(p))
            r.Changes.Add("Intestatura di coda non disponibile: la linea non ha un fermo scomparente abilitato. Impostata l'intestatura di testa.");
        SyncAutoSensors(p, r);
        CheckMandatoryStrapping(p, r);
        return r;
    }

    // ================================================================== 1. Nomi progressivi

    private sealed record Category(string Prefix, string Label, IList<ComponentBase> Items, Func<ComponentBase, double> Key, bool Reorder);

    private static void FixIds(LineProject p, PreparationReport r)
    {
        var generic = p.Photocells.Where(x => !x.IsEntryPhotocell && !x.IsAutoGenerated).Cast<ComponentBase>().ToList();
        var cats = new List<Category>
        {
            new("M", "Moduli", p.Sections.Cast<ComponentBase>().ToList(), c => ((RollerSection)c).StartMm, true),
            new("L", "Legatrici", p.Strappers.Cast<ComponentBase>().ToList(), c => ((StrapperConfig)c).PositionMm, true),
            new("FC", "Fotocellule", generic, c => ((PhotocellConfig)c).PositionMm, true),
            new("FM", "Fermi scomparenti", p.IntermediateStops.Cast<ComponentBase>().ToList(), c => ((IntermediateStopConfig)c).PositionMm, true),
            new("B", "Bilici", p.Scales.Cast<ComponentBase>().ToList(), c => ((WeighingScaleConfig)c).StartMm, true),
            new("T", "Tipologie pacco", p.PackageTypes.Cast<ComponentBase>().ToList(), _ => 0, false),
            new("R", "Regole", p.Rules.Cast<ComponentBase>().ToList(), _ => 0, false)
        };
        var fixedIds = new List<ComponentBase> { p.Stopper, p.Transfer, p.BundleClamp, p.Compactor, p.Rejector, p.StrappingEncoder };
        fixedIds.AddRange(p.Photocells.Where(x => x.IsEntryPhotocell || x.IsAutoGenerated));

        var map = new Dictionary<string, string>(StringComparer.Ordinal);
        var used = new HashSet<string>(fixedIds.Select(c => c.Id).Where(s => !string.IsNullOrWhiteSpace(s)), StringComparer.Ordinal);
        foreach (var cat in cats)
        {
            if (cat.Items.Count == 0) continue;
            var ordered = cat.Items.OrderBy(cat.Key).ThenBy(c => cat.Items.IndexOf(c)).ToList();
            var pattern = new Regex("^" + Regex.Escape(cat.Prefix) + @"(\d+)$");
            var counts = cat.Items.GroupBy(c => c.Id ?? "").ToDictionary(g => g.Key, g => g.Count());
            bool bad = cat.Items.Any(c => string.IsNullOrWhiteSpace(c.Id) || counts[c.Id] > 1 || used.Contains(c.Id));
            bool allGeneric = cat.Items.All(c => string.IsNullOrWhiteSpace(c.Id) || pattern.IsMatch(c.Id));
            bool outOfOrder = cat.Reorder && allGeneric && ordered.Select((c, i) => c.Id == cat.Prefix + (i + 1)).Any(ok => !ok);
            if (!bad && !outOfOrder) { foreach (var c in cat.Items) used.Add(c.Id); continue; }

            var renamed = new List<string>();
            if (cat.Reorder && allGeneric)
            {
                // Rinumerazione progressiva completa lungo la linea
                var seen = new HashSet<string>(StringComparer.Ordinal);
                for (int i = 0; i < ordered.Count; i++)
                {
                    var c = ordered[i];
                    string old = c.Id ?? "";
                    string nu = cat.Prefix + (i + 1);
                    while (used.Contains(nu)) nu += "_";
                    if (old.Length > 0 && seen.Add(old) && old != nu) map.TryAdd(old, nu);
                    if (old != nu) { renamed.Add($"{(old.Length > 0 ? old : "(vuoto)")}→{nu}"); RenameName(c, old, nu); c.Id = nu; }
                }
                foreach (var c in ordered) used.Add(c.Id);
            }
            else
            {
                // Solo gli identificativi vuoti o duplicati ricevono il primo progressivo libero
                var seen = new HashSet<string>(StringComparer.Ordinal);
                foreach (var c in ordered)
                {
                    string old = c.Id ?? "";
                    if (old.Length > 0 && !used.Contains(old) && seen.Add(old)) continue;
                    int n = 1;
                    while (used.Contains(cat.Prefix + n) || cat.Items.Any(x => x != c && x.Id == cat.Prefix + n)) n++;
                    string nu = cat.Prefix + n;
                    renamed.Add($"{(old.Length > 0 ? old : "(vuoto)")}→{nu}");
                    RenameName(c, old, nu);
                    c.Id = nu;
                    used.Add(nu);
                    seen.Add(nu);
                }
                foreach (var c in cat.Items) used.Add(c.Id);
            }
            if (renamed.Count > 0) r.Changes.Add($"{cat.Label} rinominati con progressivo lungo la linea: {string.Join(", ", renamed)}");
        }
        if (map.Count > 0) RemapReferences(p, map);
    }

    private static readonly Regex GenericName = new(@"^(|Legatrice( KNCA| SMA)?( \S+)?|Reggettatrice( SMA)?( \S+)?|Modulo( \S+)?|Nuova fotocellula|Fermo scomparente( \S+)?|Bilico( \S+)?)( \(copia\))*$", RegexOptions.CultureInvariant);

    private static void RenameName(ComponentBase c, string oldId, string newId)
    {
        if (!GenericName.IsMatch(c.Name ?? "") && !(c.Name ?? "").Contains("(copia)", StringComparison.Ordinal)) return;
        string num = Regex.Match(newId, @"\d+$").Value;
        c.Name = c switch
        {
            StrapperConfig s => (s.MachineType == StrapperMachineType.SMA ? "Reggettatrice SMA " : "Legatrice KNCA ") + num,
            RollerSection => "Modulo " + num,
            PhotocellConfig => "Fotocellula " + newId,
            IntermediateStopConfig => "Fermo scomparente " + num,
            WeighingScaleConfig => "Bilico " + num,
            _ => c.Name
        };
    }

    /// <summary>Aggiorna tutti i riferimenti agli identificativi rinominati (zone, fotocellule, legatrici, dispositivi, regole, piani).</summary>
    private static void RemapReferences(LineProject p, IReadOnlyDictionary<string, string> map)
    {
        string M(string? id) => id != null && map.TryGetValue(id, out var n) ? n : id ?? string.Empty;
        foreach (var s in p.Sections) if (!string.IsNullOrWhiteSpace(s.CommandZoneId)) s.CommandZoneId = M(s.CommandZoneId);
        foreach (var pc in p.Photocells) pc.ControlledInverterId = M(pc.ControlledInverterId);
        p.StrappingStation.InverterId = M(p.StrappingStation.InverterId);
        foreach (var rule in p.Rules)
        {
            rule.TargetInverterId = M(rule.TargetInverterId);
            RemapCondition(rule.Condition, M);
        }
        foreach (var plan in p.StrappingStation.ManualPlans)
        {
            plan.PackageTypeId = M(plan.PackageTypeId);
            foreach (var st in plan.Stops) foreach (var a in st.Assignments) a.StrapperId = M(a.StrapperId);
        }
        p.Infeed.TypeSequence = p.Infeed.TypeSequence.Select(M).ToList();
        p.Rejector.RejectTypeIds = p.Rejector.RejectTypeIds.Select(M).ToList();
        var devices = new List<SequenceDeviceConfig> { p.BundleClamp, p.Compactor, p.Rejector };
        devices.AddRange(p.Scales);
        foreach (var d in devices)
        {
            d.StartConsent = RemapText(d.StartConsent, M);
            d.StopCondition = RemapText(d.StopCondition, M);
        }
    }

    private static string RemapText(string text, Func<string?, string> m)
    {
        if (string.IsNullOrWhiteSpace(text)) return text;
        try
        {
            var c = ConditionText.Parse(text);
            RemapCondition(c, m);
            return ConditionText.Format(c);
        }
        catch (FormatException) { return text; }
    }

    private static void RemapCondition(LogicCondition? c, Func<string?, string> m)
    {
        switch (c)
        {
            case AndCondition a: foreach (var ch in a.Children) RemapCondition(ch, m); break;
            case OrCondition o: foreach (var ch in o.Children) RemapCondition(ch, m); break;
            case NotCondition n: RemapCondition(n.Child, m); break;
            case PhotocellCondition pc: pc.PhotocellId = m(pc.PhotocellId); break;
            case InverterRunningCondition ir: ir.InverterId = m(ir.InverterId); break;
            case ZoneOccupiedCondition zo: zo.InverterId = m(zo.InverterId); break;
            case GapAheadLessThanCondition g: g.InverterId = m(g.InverterId); break;
            case StrapperBusyCondition sb: sb.StrapperId = m(sb.StrapperId); break;
            case DeviceStateCondition d: d.DeviceId = m(d.DeviceId); break;
        }
    }

    // ================================================================== 2. La stazione segue le legatrici

    private static void FixStation(LineProject p, PreparationReport r)
    {
        var st = p.StrappingStation;
        var enabled = p.Strappers.Where(s => s.IsEnabled).OrderBy(s => s.PositionMm).ToList();
        bool want = enabled.Count > 0;
        if (st.IsEnabled != want)
        {
            st.IsEnabled = want;
            r.Changes.Add(want ? "Stazione di legatura abilitata: ci sono legatrici abilitate, quindi ogni pacco deve essere legato."
                               : "Stazione di legatura disattivata: tutte le legatrici sono disabilitate, i pacchi vanno al trasferitore senza legatura.");
        }
        if (!want) return;

        var topo = new LineTopology(p);
        var zones = enabled.Select(s => topo.ZoneAt(s.PositionMm / 1000.0)).ToList();
        if (zones.Any(z => z == null))
        {
            r.Errors.Add($"Legatrice {enabled[zones.FindIndex(z => z == null)].Id} fuori dalle vie a rulli: spostala sopra un modulo.");
            return;
        }
        var distinct = zones.Distinct().OrderBy(z => z!.Index).ToList();
        if (distinct.Count > 1)
        {
            // Le macchine di legatura lavorano su un pacco fermo: i moduli che le portano diventano una sola zona di comando
            int from = distinct[0]!.Index, to = distinct[^1]!.Index;
            var mods = topo.Zones.Where(z => z.Index >= from && z.Index <= to).SelectMany(z => z.Sections).ToList();
            string id = distinct[0]!.Id;
            foreach (var m in mods) m.CommandZoneId = id;
            r.Changes.Add($"Le legatrici stanno su più moduli ({string.Join(", ", mods.Select(m => m.Id))}): uniti in un'unica zona di comando {id} per la stazione di legatura.");
            topo = new LineTopology(p);
        }
        var zone = topo.ZoneAt(enabled[0].PositionMm / 1000.0)!;
        if (topo.Zone(st.InverterId) != zone)
        {
            string old = string.IsNullOrWhiteSpace(st.InverterId) ? "(nessuno)" : st.InverterId;
            st.InverterId = zone.Id;
            r.Changes.Add($"Zona della stazione di legatura: {old} → {zone.Id} (il modulo che porta le legatrici).");
        }
        var stopZone = topo.ZoneAt(p.Stopper.PositionMm / 1000.0 - 1e-6) ?? topo.Zones[^1];
        if (stopZone == zone)
            r.Errors.Add($"Le legatrici sono nella zona del fermo finale ({zone.Id}): spostale su un modulo a monte del trasferitore.");
    }

    // ================================================================== 3. Collegamenti e posizioni

    private static void FixReferences(LineProject p, PreparationReport r)
    {
        var topo = new LineTopology(p);
        foreach (var pc in p.Photocells.Where(x => x.Action != PhotocellAction.None && !x.IsAutoGenerated))
        {
            if (topo.Zone(pc.ControlledInverterId) != null) continue;
            var z = topo.ZoneAt(pc.PositionMm / 1000.0);
            if (z == null) continue;
            string old = string.IsNullOrWhiteSpace(pc.ControlledInverterId) ? "(nessuno)" : pc.ControlledInverterId;
            pc.ControlledInverterId = z.Id;
            r.Changes.Add($"{pc.Id}: modulo comandato {old} inesistente → {z.Id} (il modulo in cui si trova).");
        }
    }

    /// <summary>Stringifascio e compattatore stanno in ingresso alla prima macchina (default 450 mm a monte).</summary>
    private static bool FixClampPositions(LineProject p, PreparationReport r, bool force)
    {
        var first = ProjectNormalizer.FirstStrappingMachine(p);
        if (first == null) return false;
        var topo = new LineTopology(p);
        var zone = topo.Zone(p.StrappingStation.InverterId);
        double def = first.PositionMm - ProjectNormalizer.DefaultClampOffsetMm;
        bool changed = false;
        foreach (var (pos, set, label, id) in new (double, Action<double>, string, string)[]
        {
            (p.BundleClamp.PositionMm, v => p.BundleClamp.PositionMm = v, "Stringifascio", p.BundleClamp.Id),
            (p.Compactor.PositionMm, v => p.Compactor.PositionMm = v, "Compattatore", p.Compactor.Id)
        })
        {
            bool enabled = id == p.BundleClamp.Id ? p.BundleClamp.IsEnabled : p.Compactor.IsEnabled;
            if (!enabled || Math.Abs(pos - def) < Tol) continue;
            double x = pos / 1000.0;
            bool outside = zone == null || x < zone.StartM - 1e-9 || x > zone.EndM + 1e-9;
            // Lo stringifascio deve stare a monte della prima macchina; il compattatore può stare anche tra le macchine
            bool downstream = id == p.BundleClamp.Id && pos >= first.PositionMm;
            if (!force && pos > 0 && !outside && !downstream) continue;
            set(def);
            changed = true;
            r.Changes.Add($"{label} {id}: {pos.ToString("0", Ci)} → {def.ToString("0", Ci)} mm (in ingresso alla prima macchina {first.Id}, 450 mm a monte)");
        }
        return changed;
    }

    /// <summary>Riallinea i sensori aggiunti automaticamente quando trasferitore o macchine vengono spostati; aggiunge quelli mancanti.</summary>
    private static void SyncAutoSensors(LineProject p, PreparationReport r)
    {
        if (!p.Simulation.AutoAddProcessSensors) return;
        var topo = new LineTopology(p);
        foreach (var pc in p.Photocells.Where(x => x.IsAutoGenerated && x.Purpose == PhotocellPurpose.TransferStop).ToList())
        {
            double x = Math.Round(p.Transfer.PositionMm - ProjectNormalizer.TransferStopDistanceMm(p));
            var z = topo.ZoneAt(x / 1000.0);
            if (z == null) { p.Photocells.Remove(pc); r.Changes.Add($"{pc.Id}: rimossa (la posizione davanti al trasferitore è fuori linea)."); continue; }
            if (Math.Abs(pc.PositionMm - x) < Tol && pc.ControlledInverterId == z.Id) continue;
            r.Changes.Add($"{pc.Id}: fotocellula di arresto davanti al trasferitore {pc.PositionMm.ToString("0", Ci)} → {x.ToString("0", Ci)} mm (comanda {z.Id}).");
            pc.PositionMm = x;
            pc.ControlledInverterId = z.Id;
        }
        var first = ProjectNormalizer.FirstStrappingMachine(p);
        var refs = p.Photocells.Where(x => x.IsAutoGenerated && x.Purpose == PhotocellPurpose.StrappingReference).ToList();
        if (first == null)
        {
            foreach (var pc in refs) { p.Photocells.Remove(pc); r.Changes.Add($"{pc.Id}: rimossa (nessuna macchina di legatura abilitata)."); }
            if (p.StrappingEncoder.IsAutoGenerated && p.StrappingEncoder.IsEnabled) { p.StrappingEncoder.IsEnabled = false; r.Changes.Add($"{p.StrappingEncoder.Id}: disattivato (nessuna macchina di legatura abilitata)."); }
        }
        else
        {
            var host = topo.ZoneAt(first.PositionMm / 1000.0);
            double pitch = host?.Sections.FirstOrDefault()?.RollerPitchMm ?? 300;
            double enc = Math.Round(first.PositionMm - first.FootprintLengthMm / 2 - pitch);
            // La fotocellula di riferimento (300 mm prima dell'encoder) non va mai a monte di FC0 + 100 mm
            enc = Math.Max(enc, StrappingAreaRules.MinReferencePhotocellMm(p) + ProjectNormalizer.ReferencePhotocellOffsetMm);
            if (p.StrappingEncoder.IsAutoGenerated && p.StrappingEncoder.IsEnabled && Math.Abs(p.StrappingEncoder.PositionMm - enc) >= Tol)
            {
                r.Changes.Add($"{p.StrappingEncoder.Id}: encoder {p.StrappingEncoder.PositionMm.ToString("0", Ci)} → {enc.ToString("0", Ci)} mm (primo rullo prima di {first.Id}).");
                p.StrappingEncoder.PositionMm = enc;
            }
            double x = Math.Round(p.StrappingEncoder.PositionMm - ProjectNormalizer.ReferencePhotocellOffsetMm);
            foreach (var pc in refs)
            {
                string zone = p.StrappingStation.InverterId;
                if (Math.Abs(pc.PositionMm - x) < Tol && pc.ControlledInverterId == zone) continue;
                r.Changes.Add($"{pc.Id}: fotocellula di riferimento encoder {pc.PositionMm.ToString("0", Ci)} → {x.ToString("0", Ci)} mm.");
                pc.PositionMm = x;
                pc.ControlledInverterId = zone;
            }
        }
        foreach (var a in ProjectNormalizer.EnsureProcessSensors(p)) r.Changes.Add("Aggiunto: " + a);
    }

    // ================================================================== 4. Legatura obbligatoria

    private static void CheckMandatoryStrapping(LineProject p, PreparationReport r)
    {
        if (!p.StrappingStation.IsEnabled || r.HasErrors) return;
        var types = p.Infeed.TypeSequence.Select(id => p.PackageTypes.FirstOrDefault(t => t.Id == id)).Where(t => t != null).Cast<PackageType>().Distinct().ToList();
        if (types.Count == 0 && p.PackageTypes.Count > 0) types.Add(p.PackageTypes[0]);
        var problems = Infeasible(p, types);
        if (problems.Count > 0 && FixClampPositions(p, r, force: true))
        {
            SyncAutoSensors(p, r);
            problems = Infeasible(p, types);
        }
        foreach (var (t, why) in problems)
            r.Errors.Add($"Con le legatrici abilitate ogni pacco deve essere legato: il pacco {t.Id} ({t.LengthMm.ToString("0", Ci)} mm) non è legabile con la disposizione attuale ({why}). " +
                         "Sposta le legatrici (o le legature del pacco) oppure disabilita tutte le legatrici per mandarlo al trasferitore senza legatura.");
    }

    private static List<(PackageType Type, string Why)> Infeasible(LineProject p, List<PackageType> types)
    {
        var list = new List<(PackageType, string)>();
        var topo = new LineTopology(p);
        if (topo.StrappingZone == null) { list.AddRange(types.Select(t => (t, "zona di legatura non valida"))); return list; }
        foreach (var t in types)
        {
            if (t.StrapPositionsMm.Count == 0) { list.Add((t, "il pacco non ha legature definite")); continue; }
            var cmp = StrappingPlanner.Compare(p, topo, t);
            if (!cmp.Selected.IsFeasible) list.Add((t, cmp.Selected.InfeasibleReason ?? cmp.Error ?? "nessun piano di legatura"));
        }
        return list;
    }
}
