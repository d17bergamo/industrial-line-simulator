/// <summary>Esito dell'apertura di un progetto salvato: progetto aggiornato e modifiche che l'aggiornamento comporta.</summary>
public sealed class UpgradeReport
{
    public required LineProject Project { get; init; }
    /// <summary>Versione dello schema con cui era stato salvato il file.</summary>
    public int FileSchemaVersion { get; init; }
    /// <summary>Correzioni delle regole automatiche (descrizioni leggibili).</summary>
    public List<string> RuleChanges { get; } = new();
    /// <summary>Valori cambiati rispetto al file, componente per componente.</summary>
    public List<string> ValueChanges { get; } = new();
    public bool HasChanges => RuleChanges.Count > 0 || ValueChanges.Count > 0;
    public bool IsOlderSchema => FileSchemaVersion < LineProject.CurrentSchemaVersion;
}

/// <summary>
/// Aggiornamento dei progetti salvati con regole o versioni precedenti. Il progetto letto dal file viene confrontato con
/// quello aggiornato (adeguamenti di apertura + controlli automatici): l'app mostra l'elenco e chiede conferma
/// prima di modificarlo, e il file originale non viene sovrascritto.
/// </summary>
public static class ProjectUpgrade
{
    /// <summary>Adeguamenti applicati a ogni progetto aperto (prima erano solo nell'app, senza avviso).</summary>
    public static void Normalize(LineProject p)
    {
        GroupInheritance.MarkAllCustomized(p);              // fotocellule, legatrici e bilici con valori propri restano personalizzati
        RollerGroups.SyncElevation(p, fromGroup: false);
        ProjectNormalizer.AlignEntryPhotocell(p);           // la prima fotocellula sta sullo zero della via rulli
        RollerGroups.MarkCustomized(p);                     // i moduli diversi dal padre restano personalizzati
        LineReflow.ApplyDefaultRollerGeometry(p);           // passo 1250 mm e diametro 268 mm al posto dei vecchi default
        LineReflow.EnforceOverhang(p);                      // sporgenza terminale = metà passo rulli
        PackageNaming.MigrateLegacyIds(p);                  // identificativi pacco "P12 (Wire)"
        StrapperTrack.ClampStrappersToTrackStart(p);        // legatrici ad almeno 1 m dall'inizio della via rulli
        LayoutRules.SnapIntermediateStops(p);
        StrapperTrack.EnsureMinimumTrack(p);                // almeno due rulli di via dopo l'ultima legatrice
        ProjectNormalizer.AlignStopperToLastRoller(p);      // il fermo finale sta sempre dopo l'ultimo rullo
    }

    /// <summary>Legge il file, prepara la versione aggiornata e confronta le due.</summary>
    public static UpgradeReport Check(string json)
    {
        int version = 1;
        try { version = JsonNode.Parse(json)?["schemaVersion"]?.GetValue<int>() ?? 1; } catch { /* letto sotto */ }
        var original = ProjectSerializer.Deserialize(json, normalize: false);
        var upgraded = ProjectSerializer.Deserialize(json);
        Normalize(upgraded);
        var fix = ProjectAutoFix.Run(upgraded);
        var r = new UpgradeReport { Project = upgraded, FileSchemaVersion = version };
        r.RuleChanges.AddRange(fix.Messages);
        r.ValueChanges.AddRange(ProjectDiff.Describe(original, upgraded));
        return r;
    }
}

/// <summary>Differenze tra due progetti, scritte per componente: "FC1 · Posizione in linea: 1200 → 1350 mm".</summary>
public static class ProjectDiff
{
    private static readonly CultureInfo Ci = CultureInfo.InvariantCulture;
    /// <summary>Campi di servizio che non cambiano il comportamento della linea.</summary>
    private static readonly HashSet<string> Ignored = new(StringComparer.OrdinalIgnoreCase) { "schemaVersion", "overrideGroup", "isAutoGenerated", "projectId" };

    public static List<string> Describe(LineProject before, LineProject after, int max = 60)
    {
        var a = Flatten(before);
        var b = Flatten(after);
        var lines = new List<string>();
        var addedComp = b.Keys.Select(k => k.Comp).Distinct().Except(a.Keys.Select(k => k.Comp).Distinct()).ToHashSet();
        var removedComp = a.Keys.Select(k => k.Comp).Distinct().Except(b.Keys.Select(k => k.Comp).Distinct()).ToHashSet();
        foreach (var c in addedComp.Where(c => c.Contains('['))) lines.Add($"Aggiunto {CompName(c)}");
        foreach (var c in removedComp.Where(c => c.Contains('['))) lines.Add($"Tolto {CompName(c)}");
        foreach (var key in a.Keys.Union(b.Keys).OrderBy(k => k.Comp).ThenBy(k => k.Field))
        {
            if (addedComp.Contains(key.Comp) || removedComp.Contains(key.Comp)) continue;
            a.TryGetValue(key, out var va);
            b.TryGetValue(key, out var vb);
            if (va == vb) continue;
            lines.Add($"{CompName(key.Comp)} · {Label(key.Field)}: {Val(va)} → {Val(vb)}");
            if (lines.Count >= max) { lines.Add("…"); break; }
        }
        return lines;
    }

    private static Dictionary<(string Comp, string Field), string?> Flatten(LineProject p)
    {
        var node = JsonNode.Parse(JsonSerializer.Serialize(p, ProjectSerializer.Options))!;
        var d = new Dictionary<(string, string), string?>();
        Walk(node, "Progetto", "", d);
        return d;
    }

    private static void Walk(JsonNode? n, string comp, string field, Dictionary<(string, string), string?> d)
    {
        switch (n)
        {
            case JsonObject o:
                foreach (var (k, v) in o)
                {
                    if (Ignored.Contains(k)) continue;
                    if (v is JsonObject && field.Length == 0) Walk(v, comp == "Progetto" ? k : comp + "." + k, "", d);   // sotto-oggetto = componente
                    else Walk(v, comp, field.Length == 0 ? k : field + "." + k, d);
                }
                break;
            case JsonArray arr:
                for (int i = 0; i < arr.Count; i++)
                {
                    if (arr[i] is JsonObject eo && eo["id"]?.GetValue<string>() is string id && id.Length > 0)
                        Walk(eo, $"{(field.Length == 0 ? comp : field)}[{id}]", "", d);
                    else Walk(arr[i], comp, $"{field}[{i}]", d);
                }
                if (arr.Count == 0) d[(comp, field)] = "[]";
                break;
            default:
                d[(comp, field)] = n?.ToJsonString();
                break;
        }
    }

    private static string CompName(string comp)
    {
        int i = comp.LastIndexOf('[');
        if (i < 0) return Label(comp);
        string id = comp[(i + 1)..].TrimEnd(']');
        return id;
    }

    private static readonly Lazy<Dictionary<string, string>> Labels = new(() =>
    {
        var d = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var t in typeof(LineProject).Assembly.GetTypes())
            foreach (var pr in t.GetProperties(BindingFlags.Public | BindingFlags.Instance))
                if (pr.GetCustomAttribute<UiPropertyAttribute>() is { } a && !d.ContainsKey(pr.Name))
                    d[pr.Name] = a.Unit.Length > 0 ? $"{a.DisplayName} [{a.Unit}]" : a.DisplayName;
        return d;
    });

    private static string Label(string field)
    {
        string last = field.Split('.').Last();
        int b = last.IndexOf('[');
        string name = b >= 0 ? last[..b] : last;
        return Labels.Value.TryGetValue(name, out var l) ? l + (b >= 0 ? last[b..] : "") : field;
    }

    private static string Val(string? json)
    {
        if (json == null) return "(assente)";
        if (double.TryParse(json, NumberStyles.Float, Ci, out var v)) return Math.Round(v, 2).ToString("0.##", Ci);
        return json.Trim('"');
    }
}
