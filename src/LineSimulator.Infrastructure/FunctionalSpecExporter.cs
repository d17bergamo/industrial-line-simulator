namespace LineSimulator.Infrastructure;

/// <summary>
/// Specifica tecnica funzionale dell'area (formato Word), generata solo su richiesta esplicita dell'utente:
/// layout e macchine, sequenze di funzionamento per tipologia (single/double banking), regole logiche di controllo,
/// tempi di default e interblocchi, fotocellule e inverter con posizione e scopo, risultati di simulazione.
/// </summary>
public static class FunctionalSpecExporter
{
    private static readonly CultureInfo It = CultureInfo.GetCultureInfo("it-IT");
    private static string N(double v, string f = "0.##") => v.ToString(f, It);

    public static void Export(LineProject source, SimulationResults? results, string path) => File.WriteAllBytes(path, Build(source, results));

    /// <summary>Documento Word in memoria (usato anche dalla versione web).</summary>
    public static byte[] Build(LineProject source, SimulationResults? results)
    {
        using var ms = new MemoryStream();
        Write(source, results, ms);
        return ms.ToArray();
    }

    private static void Write(LineProject source, SimulationResults? results, Stream stream)
    {
        var p = ProjectSerializer.Clone(source);
        ProjectNormalizer.EnsureProcessSensors(p);
        var topo = new LineTopology(p);
        var logic = ControlLogicGenerator.Generate(p);

        using var doc = WordprocessingDocument.Create(stream, WordprocessingDocumentType.Document);
        var main = doc.AddMainDocumentPart();
        AddStyles(main);
        var body = new Body();
        main.Document = new Document(body);

        body.Append(Para("Specifica tecnica funzionale", "Title"));
        body.Append(Para($"Area: {p.Name}"));
        if (!string.IsNullOrWhiteSpace(p.Description)) body.Append(Para(p.Description));
        body.Append(Para("Documento generato dal simulatore di linea su richiesta dell'utente. Strumento di progettazione e simulazione: " +
                         "protezioni e interblocchi di sicurezza reali vanno verificati e implementati nel PLC e nei circuiti di sicurezza della macchina.", "Note"));

        // 1. Layout e macchine
        body.Append(Para("1. Descrizione del layout e delle macchine", "Heading1"));
        body.Append(Para("Tutte le quote sono misurate lungo la linea a partire dall'inizio linea; la fotocellula di ingresso è il punto zero di identificazione dei pacchi."));
        body.Append(Para("1.1 Vie a rulli e inverter", "Heading2"));
        body.Append(MakeTable(new[] { "Inverter (zona)", "Moduli", "Inizio [mm]", "Fine [mm]", "Lunghezza [m]", "V alta / bassa [m/s]", "Acc / dec [m/s²]", "Arresto automatico" },
            topo.Zones.Select(z => new[]
            {
                z.Id, string.Join(", ", z.Sections.Select(s => s.Id)), N(z.StartM * 1000, "0"), N(z.EndM * 1000, "0"), N(z.LengthM),
                $"{N(z.Inverter.HighSpeed)} / {N(z.Inverter.LowSpeed)}", $"{N(z.Inverter.Acceleration)} / {N(z.Inverter.Deceleration)}",
                z.Inverter.AutoStopWhenEmpty ? "sì (corsa a vuoto = lunghezza)" : "no"
            })));
        body.Append(Para($"Numero di inverter: {topo.Zones.Count}. Numero di moduli di via a rulli: {p.Sections.Count}."));

        body.Append(Para("1.2 Macchine di legatura e dispositivi", "Heading2"));
        var rows = new List<string[]>();
        foreach (var s in p.Strappers)
            rows.Add(new[]
            {
                s.Id, s.MachineType == StrapperMachineType.SMA ? "Reggettatrice " + s.Model : "Legatrice " + s.Model, N(s.PositionMm, "0"),
                $"{(s.MachineType == StrapperMachineType.SMA ? "riarmo" : "carica filo")} {N(s.ArmingTimeS)} s; ciclo {N(s.StrappingTimeS)} s", s.IsEnabled ? "abilitata" : "disabilitata"
            });
        foreach (var (kid, kpos) in LayoutRules.BundleClampPositions(p))
            rows.Add(new[] { kid, "Stringifascio " + p.BundleClamp.Model + (p.BundleClamp.PerMachine ? " (uno per macchina, comando comune)" : ""), N(kpos, "0"),
                $"chiusura {N(p.BundleClamp.CloseTimeS)} s, mantenimento {N(p.BundleClamp.HoldTimeS)} s, apertura {N(p.BundleClamp.OpenTimeS)} s", "abilitato" });
        if (p.Compactor.IsEnabled)
            rows.Add(new[] { p.Compactor.Id, "Compattatore laterale", N(p.Compactor.PositionMm, "0"),
                $"chiusura {N(p.Compactor.CloseTimeS)} s, mantenimento {N(p.Compactor.HoldTimeS)} s, apertura {N(p.Compactor.OpenTimeS)} s", "abilitato" });
        if (p.StrappingEncoder.IsEnabled)
            rows.Add(new[] { p.StrappingEncoder.Id, "Encoder incrementale di legatura", N(p.StrappingEncoder.PositionMm, "0"), $"risoluzione {N(p.StrappingEncoder.ResolutionMm)} mm", p.StrappingEncoder.IsAutoGenerated ? "aggiunto in automatico" : "" });
        if (p.Rejector.IsEnabled)
            rows.Add(new[] { p.Rejector.Id, p.Rejector.Name, N(p.Rejector.PositionMm, "0"), $"espulsione {N(p.Rejector.EjectTimeS)} s, ritorno {N(p.Rejector.ReturnTimeS)} s", "abilitata" });
        rows.Add(new[] { p.Stopper.Id, "Fermo finale (stopper)", N(p.Stopper.PositionMm, "0"), $"allineamento {N(p.Stopper.AlignmentTimeS + p.Stopper.HeadingTimeS)} s a {N(p.Stopper.AlignmentRollerSpeed)} m/s", "" });
        foreach (var s in p.IntermediateStops.Where(x => x.IsEnabled))
            rows.Add(new[] { s.Id, "Fermo scomparente", N(s.PositionMm, "0"), $"intestatura di {(s.Reference == StopReference.Head ? "testa" : "coda")}, {N(s.AlignmentTimeS)} s", "" });
        rows.Add(new[] { p.Transfer.Id, "Trasferitore sollevabile", $"{N(p.Transfer.PositionMm, "0")} – {N(p.Transfer.EndMm, "0")}",
            $"sollevamento {N(p.Transfer.LiftTimeS)} s, traslazione {N(p.Transfer.EffectiveTranslationTimeS)} s, abbassamento {N(p.Transfer.LowerTimeS)} s, deposito {N(p.Transfer.DepositTimeS)} s; fino a {Math.Max(1, p.Transfer.BatchSize)} pacchi per ciclo", "" });
        foreach (var b in p.Scales.Where(x => x.IsEnabled))
            rows.Add(new[] { b.Id, "Bilico di pesatura", $"{N(b.StartMm, "0")} – {N(b.EndMm, "0")}",
                $"stabilizzazione {N(b.StabilizationTimeS)} s, acquisizione {N(b.AcquisitionTimeS)} s, scarico {N(b.ReleaseTimeS)} s; pacchi corti ≤ {N(b.ShortPackageMaxLengthMm, "0")} mm in posizione intermedia", "" });
        body.Append(MakeTable(new[] { "ID", "Macchina", "Posizione [mm]", "Tempi", "Note" }, rows));

        body.Append(Para("1.3 Fotocellule", "Heading2"));
        body.Append(MakeTable(new[] { "ID", "Nome", "Posizione [mm]", "Zona", "Scopo", "Regole" },
            logic.Photocells.Select(x => new[] { x.Id, x.Name + (x.AutoGenerated ? " (automatica)" : ""), N(x.PositionMm, "0"), x.Zone, x.Purpose, x.Rules })));

        // 2. Pacchi
        body.Append(Para("2. Tipologie di pacco", "Heading1"));
        body.Append(MakeTable(new[] { "ID", "Nome", "Lunghezza [mm]", "Peso [kg]", "Tipo di legatura", "Legature dalla testa [mm]" },
            p.PackageTypes.Select(t => new[]
            {
                t.Id, t.Name, N(t.LengthMm, "0"), N(t.WeightKg, "0"), t.BindingType == BindingType.SteelStrap ? "reggia d'acciaio (reggettatrice)" : "filo (KNCA)",
                string.Join(" / ", t.StrapPositionsMm.Select(x => N(x, "0")))
            })));

        // 3. Sequenze
        body.Append(Para("3. Sequenze di funzionamento", "Heading1"));
        body.Append(Para("3.1 Ingresso, trasporto e accumulo", "Heading2"));
        foreach (var line in new[]
        {
            "Il pacco viene identificato dalla fotocellula di ingresso (fronte di salita) e ne viene misurata la lunghezza (fronte di discesa).",
            "Ingresso un pacco alla volta: il pacco fermo sulla fotocellula di ingresso parte quando il precedente è legato e la sua coda ha liberato la fotocellula di uscita legatura e il primo rullo dello svincolo (che è sull'inverter della via di legatura).",
            "All'avvio tutte le vie a rulli con arresto automatico sono vuote e ferme: si accendono solo quando arriva il pacco.",
            "Ogni inverter si spegne quando i suoi rulli hanno compiuto una corsa pari alla lunghezza della zona senza che le sue fotocellule rilevino pacchi; riparte quando la fotocellula a monte rileva l'arrivo di un pacco.",
            "Accumulo: una zona si ferma quando la sua fotocellula di accumulo è occupata e la zona a valle non dà il consenso; lo spazio di arresto (tempo di risposta + frenatura) è verificato dentro la zona.",
            $"Il materiale si ferma sulla fotocellula di arresto posta {N(ProjectNormalizer.TransferStopDistanceMm(p), "0")} mm prima del trasferitore (almeno 2 m, o lo spazio per fermarsi dalla velocità massima) finché il trasferitore non è a riposo (anche in abbassamento, deposito e ritorno), con l'area del trasferitore occupata e, in double banking, finché il primo pacco non è intestato; riparte con il trasferitore a riposo e un posto libero."
        }) body.Append(Bullet(line));

        if (p.StrappingStation.IsEnabled && topo.StrappingZone != null)
        {
            body.Append(Para("3.2 Stazione di legatura", "Heading2"));
            var steps = new List<string>
            {
                "La testa del pacco impegna la fotocellula di riferimento: si azzera l'encoder e le legatrici a filo iniziano la carica del filo.",
                "Il pacco viene posizionato alla quota encoder della fermata (profilo di posizionamento con frenatura calcolata sulla distanza residua)."
            };
            if (p.Compactor.IsEnabled) steps.Add($"Con la via a rulli ferma il compattatore chiude ({N(p.Compactor.CloseTimeS)} s), conferma e mantiene ({N(p.Compactor.HoldTimeS)} s).");
            if (p.BundleClamp.IsEnabled) steps.Add($"Lo stringifascio chiude ({N(p.BundleClamp.CloseTimeS)} s) e conferma la chiusura: solo allora può iniziare il ciclo di legatura.");
            steps.Add("Le macchine armate della fermata eseguono il ciclo (si abbassano, legano, si rialzano). Legatrice a filo: tra le legature dello stesso pattern ricarica il filo in automatico; SMA: riarmo automatico dopo ogni ciclo.");
            if (p.BundleClamp.IsEnabled) steps.Add($"A legatura terminata, dopo il mantenimento ({N(p.BundleClamp.HoldTimeS)} s), lo stringifascio apre ({N(p.BundleClamp.OpenTimeS)} s).");
            if (p.Compactor.IsEnabled) steps.Add($"Il compattatore apre ({N(p.Compactor.OpenTimeS)} s) nella fase prevista; il pacco riparte verso la fermata successiva o viene rilasciato.");
            int i = 1;
            foreach (var s in steps) body.Append(Para($"{i++}. {s}"));
            if (logic.StrappingPlans.Count > 0)
                body.Append(MakeTable(new[] { "Tipologia", "Fermata", "Testa [mm]", "Legature (macchina#legatura)", "Strategia" },
                    logic.StrappingPlans.Select(x => new[] { x.PackageType, x.Stop.ToString(It), N(x.HeadPositionMm, "0.#"), x.Tasks, x.Strategy })));
        }

        foreach (var m in p.Sections.Where(x => x.FollowsStrapping).OrderBy(x => x.StartMm))
            body.Append(Bullet(m == LayoutRules.TransferModule(p)
                ? $"Via del trasferitore {m.Id} con motori commutabili: durante una legatura di coda che porta la testa del pacco sulla via, i motori sono commutati sulla legatura quando la testa copre la fotocellula d'ingresso; se manca il consenso (trasferitore a riposo e via davanti libera) la legatura si ferma alla fotocellula e riparte al consenso, e il trasferitore non solleva finché il pacco è in legatura sulla sua via."
                : $"Svincolo {m.Id} ({N(m.LengthMm, "0")} mm) con motori commutabili: inverter proprio; mentre il pacco in legatura lo impegna per le legature di coda i motori sono commutati sull'inverter della via di legatura; altrimenti porta via il pacco già legato. Se la fermata successiva porterebbe la testa sullo svincolo ancora occupato dal pacco precedente, la legatura attende che sia libero."));
        body.Append(Para("3.3 Accumulo sul trasferitore: single e double banking", "Heading2"));
        var stops = p.IntermediateStops.Where(s => s.IsEnabled).OrderByDescending(s => s.PositionMm).ToList();
        bool tailMode = BankingOptions.ForSimulation(p).Heading == StopReference.Tail && stops.Count > 0;
        bool dblMode = BankingOptions.ForSimulation(p).Banking == AccumulationMode.DoubleBanking;
        body.Append(Para($"Impostazione della simulazione: {(dblMode ? "double banking" : "single banking")}, intestatura di {(tailMode ? "coda" : "testa")}." +
            (tailMode ? " Intestatura di coda: il pacco supera il fermo scomparente abbassato di un'extra corsa, il fermo si solleva dietro la coda e il pacco torna indietro fino alla battuta." : "")));
        // B7: banking e intestatura per tipologia dal calcolo unico del Core (stessa scelta della tabella dei pacchi e del motore)
        foreach (var t in p.PackageTypes)
        {
            var b = BankingOptions.Banking(p, t);
            var h = BankingOptions.Heading(p, t);
            string head = h == StopReference.Tail ? "intestatura di coda" : "intestatura di testa";
            if (b == AccumulationMode.DoubleBanking)
                body.Append(Bullet($"{t.Id} ({N(t.LengthMm, "0")} mm): double banking, {head} per il secondo pacco. Il primo pacco va in fondo e si intesta di testa sul fermo finale; il secondo " +
                    (stops.Count > 0 ? $"si ferma sul fermo scomparente ({string.Join(", ", stops.Select(x => x.Id))})" : $"è fermato per posizionamento (encoder) {N(p.Transfer.DoubleBankingGapMm, "0")} mm dietro al primo") +
                    " e aspetta alla fotocellula finché il primo non è intestato. I pacchi partono sempre a coppia; il trasferitore li preleva insieme."));
            else
                body.Append(Bullet($"{t.Id} ({N(t.LengthMm, "0")} mm): single banking, {head}" +
                    (h == StopReference.Tail ? (stops.Count > 0 ? $" sul fermo {stops[0].Id}" : " per posizionamento (encoder, senza fermo)") : " sul fermo finale") +
                    "; il trasferitore preleva un pacco per ciclo." +
                    (BankingOptions.ChosenBanking(p, t) == AccumulationMode.DoubleBanking && BankingOptions.DoubleBankingBlockReason(p, t) is { } why ? $" Double banking scelto ma non possibile: {why}." : "")));
        }
        double splitMm = TransferSplitRule.SplitMm(p);
        if (splitMm > 0 && topo.StopperZone is { } sz)
            body.Append(Bullet($"Via del trasferitore su due inverter: {TransferSplitRule.MonteId(sz.Id)} a monte (secondo pacco) e {TransferSplitRule.ValleId(sz.Id)} a valle (primo pacco), divisi a {N(splitMm, "0")} mm; il trasferitore sollevabile ha il doppio comando diviso nello stesso punto. Finché nessun pacco è fermo a valle i due inverter hanno lo stesso comando."));
        else if (topo.StopperZone != null)
            body.Append(Bullet("Tutti i pacchi in single banking: la via del trasferitore ha un solo inverter."));
        if (p.Scales.Any(s => s.IsEnabled) && p.Transfer.Kind == TransferKind.Lifting)
            body.Append(Bullet("Due pacchi sullo stesso bilico: pesata in due tempi. Prima si abbassa la metà a monte e si pesa il primo pacco, poi si abbassa la metà a valle e si pesa il totale; il peso del secondo è la differenza."));
        if (p.Rejector.IsEnabled)
            body.Append(Bullet($"Rigettatrice {p.Rejector.Id}: identificazione, abilitazione, posizionamento nel campo di spinta, espulsione con conferma, ritorno e consenso alla ripartenza; un pacco alla volta e solo con la sua zona libera."));
        if (p.Scales.Any(s => s.IsEnabled))
            body.Append(Bullet("Il trasferitore deposita i pacchi sui bilici liberi; pesatura (stabilizzazione e acquisizione), consenso a proseguire e scarico. Un pacco più lungo di un bilico è pesato su più bilici insieme."));

        // 4. Regole
        body.Append(Para("4. Regole logiche di controllo", "Heading1"));
        body.Append(Para(logic.Syntax));
        foreach (var g in logic.Rules.GroupBy(r => r.Group))
        {
            body.Append(Para(g.Key, "Heading2"));
            body.Append(MakeTable(new[] { "ID", "SE (condizione)", "ALLORA (azione)", "Destinazione", "Note" },
                g.Select(r => new[] { r.Id, r.Condition, r.Action, r.Target, r.Description })));
        }
        body.Append(Para("Segnali interni", "Heading2"));
        body.Append(MakeTable(new[] { "Segnale", "Definizione" }, logic.Signals.Select(s => new[] { s.Name, s.Definition })));

        // 5. Interblocchi e tempi
        body.Append(Para("5. Interblocchi e tempi di default", "Heading1"));
        foreach (var line in new[]
        {
            "L'arresto per interblocco ha priorità su ogni comando di marcia o posizionamento.",
            "Ogni dispositivo ha consenso di avvio, condizione di arresto, ritardo e timeout di conferma; oltre il timeout il dispositivo va in guasto e ripete il comando dopo il tempo di ripristino.",
            $"Legatrice a filo: ricarica filo {N(StrapperConfig.KncaArmingTimeS)} s, ciclo di legatura {N(StrapperConfig.KncaStrappingTimeS)} s. Reggettatrice: ciclo di reggettatura {N(StrapperConfig.SmaStrappingTimeS)} s, riarmo {N(StrapperConfig.SmaArmingTimeS)} s.",
            $"Stringifascio: chiusura {N(new BundleClampConfig().CloseTimeS)} s, apertura {N(new BundleClampConfig().OpenTimeS)} s. Compattatore: chiusura {N(new SideCompactorConfig().CloseTimeS)} s, apertura {N(new SideCompactorConfig().OpenTimeS)} s."
        }) body.Append(Bullet(line));

        // 6. Risultati
        if (results != null)
        {
            body.Append(Para("6. Risultati di simulazione", "Heading1"));
            body.Append(MakeTable(new[] { "Voce", "Valore" }, new[]
            {
                new[] { "Esito", results.FinishReason },
                new[] { "Pacchi entrati / usciti", $"{results.PackagesEntered} / {results.PackagesExited}" },
                new[] { "Tempo ciclo medio [s]", results.CycleTimeMeanS.HasValue ? N(results.CycleTimeMeanS.Value, "0.0") : "-" },
                new[] { "Produttività effettiva [pacchi/h]", results.PackagesPerHour.HasValue ? N(results.PackagesPerHour.Value, "0.0") : "-" },
                new[] { "Produttività effettiva [t/h]", results.TonnesPerHour.HasValue ? N(results.TonnesPerHour.Value, "0.0") : "-" },
                new[] { "Collo di bottiglia", results.BottleneckName },
                new[] { "Collisioni / allarmi", $"{results.Collisions} / {results.DeviceAlarms}" }
            }));
        }
        main.Document.Save();
    }

    // ------------------------------------------------ OpenXML

    private static Paragraph Para(string text, string? style = null)
    {
        var para = new Paragraph();
        if (style != null) para.Append(new ParagraphProperties(new ParagraphStyleId { Val = style }));
        para.Append(new Run(new Text(text) { Space = SpaceProcessingModeValues.Preserve }));
        return para;
    }

    private static Paragraph Bullet(string text) => Para("• " + text, "ListParagraph");

    private static Table MakeTable(IReadOnlyList<string> header, IEnumerable<string[]> rows)
    {
        var table = new Table();
        uint b = 4;
        table.Append(new TableProperties(
            new TableWidth { Type = TableWidthUnitValues.Pct, Width = "5000" },
            new TableBorders(
                new TopBorder { Val = BorderValues.Single, Size = b }, new BottomBorder { Val = BorderValues.Single, Size = b },
                new LeftBorder { Val = BorderValues.Single, Size = b }, new RightBorder { Val = BorderValues.Single, Size = b },
                new InsideHorizontalBorder { Val = BorderValues.Single, Size = b }, new InsideVerticalBorder { Val = BorderValues.Single, Size = b })));
        table.Append(Row(header, true));
        foreach (var r in rows) table.Append(Row(r, false));
        return table;
    }

    private static TableRow Row(IEnumerable<string> cells, bool header)
    {
        var tr = new TableRow();
        if (header) tr.Append(new TableRowProperties(new TableHeader()));
        foreach (var c in cells)
        {
            var run = new Run(new Text(c ?? string.Empty) { Space = SpaceProcessingModeValues.Preserve });
            if (header) run.PrependChild(new RunProperties(new Bold()));
            var cell = new TableCell(new Paragraph(new ParagraphProperties(new ParagraphStyleId { Val = "TableText" }), run));
            if (header) cell.PrependChild(new TableCellProperties(new Shading { Val = ShadingPatternValues.Clear, Fill = "D9E2F3", Color = "auto" }));
            tr.Append(cell);
        }
        return tr;
    }

    private static void AddStyles(MainDocumentPart main)
    {
        var part = main.AddNewPart<StyleDefinitionsPart>();
        var styles = new Styles();
        Style S(string id, string name, int halfPoints, bool bold, string color = "000000", int before = 0, int after = 120) =>
            new(new StyleName { Val = name }, new BasedOn { Val = "Normal" },
                new StyleParagraphProperties(new SpacingBetweenLines { Before = before.ToString(CultureInfo.InvariantCulture), After = after.ToString(CultureInfo.InvariantCulture) }),
                new StyleRunProperties(bold ? new Bold() : new Bold { Val = false }, new Color { Val = color }, new FontSize { Val = halfPoints.ToString(CultureInfo.InvariantCulture) }))
            { Type = StyleValues.Paragraph, StyleId = id };
        styles.Append(new Style(new StyleName { Val = "Normal" },
            new StyleRunProperties(new RunFonts { Ascii = "Calibri", HighAnsi = "Calibri" }, new FontSize { Val = "21" }),
            new StyleParagraphProperties(new SpacingBetweenLines { After = "100" }))
        { Type = StyleValues.Paragraph, StyleId = "Normal", Default = true });
        styles.Append(S("Title", "Title", 40, true, "1F3864", 0, 240));
        styles.Append(S("Heading1", "heading 1", 30, true, "1F3864", 360, 120));
        styles.Append(S("Heading2", "heading 2", 24, true, "2E74B5", 240, 80));
        styles.Append(S("Note", "Note", 18, false, "7F7F7F"));
        styles.Append(S("ListParagraph", "List Paragraph", 21, false));
        styles.Append(S("TableText", "Table Text", 18, false, "000000", 0, 0));
        part.Styles = styles;
    }
}
