    public static string ToJson(ControlLogicDocument d) =>
        JsonSerializer.Serialize(d, new JsonSerializerOptions { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping });

    private static string Csv(string? v)
    {
        v ??= string.Empty;
        return v.IndexOfAny(new[] { ';', '"', '\n' }) >= 0 ? "\"" + v.Replace("\"", "\"\"") + "\"" : v;
    }

    /// <summary>Scrive il file JSON e accanto i CSV (regole, segnali, fotocellule, inverter, piani). Restituisce i file scritti.</summary>
    public static List<string> Export(ControlLogicDocument d, string jsonPath)
    {
        var dir = Path.GetDirectoryName(Path.GetFullPath(jsonPath)) ?? ".";
        Directory.CreateDirectory(dir);
        string stem = Path.Combine(dir, Path.GetFileNameWithoutExtension(jsonPath));
        var files = new List<string>();
        void Write(string path, string text) { File.WriteAllText(path, text, new UTF8Encoding(true)); files.Add(path); }
        Write(jsonPath, ToJson(d));
        var sb = new StringBuilder("ID;Gruppo;Condizione;Azione;Destinazione;Descrizione\n");
        foreach (var r in d.Rules) sb.Append(string.Join(";", Csv(r.Id), Csv(r.Group), Csv(r.Condition), Csv(r.Action), Csv(r.Target), Csv(r.Description))).Append('\n');
        Write(stem + "_regole.csv", sb.ToString());
        sb = new StringBuilder("Segnale;Definizione\n");
        foreach (var s in d.Signals) sb.Append(Csv(s.Name)).Append(';').Append(Csv(s.Definition)).Append('\n');
        Write(stem + "_segnali.csv", sb.ToString());
        sb = new StringBuilder("ID;Nome;Posizione mm;Zona;Scopo;Regole;Automatica\n");
        foreach (var x in d.Photocells)
            sb.Append(string.Join(";", Csv(x.Id), Csv(x.Name), F(x.PositionMm, "0"), Csv(x.Zone), Csv(x.Purpose), Csv(x.Rules), x.AutoGenerated ? "sì" : "no")).Append('\n');
        Write(stem + "_fotocellule.csv", sb.ToString());
        sb = new StringBuilder("Inverter;Moduli;Inizio mm;Fine mm;Lunghezza m;Alta m/s;Bassa m/s;Acc m/s2;Dec m/s2;Fotocellula ripartenza;Regole avvio;Regole arresto\n");
        foreach (var x in d.Inverters)
            sb.Append(string.Join(";", Csv(x.Id), Csv(x.Modules), F(x.StartMm, "0"), F(x.EndMm, "0"), F(x.LengthM), F(x.HighSpeed), F(x.LowSpeed), F(x.Acceleration), F(x.Deceleration),
                Csv(x.RestartPhotocell), Csv(x.StartRules), Csv(x.StopRules))).Append('\n');
        Write(stem + "_inverter.csv", sb.ToString());
        sb = new StringBuilder("Tipologia;Fermata;Testa mm;Legature;Strategia\n");
        foreach (var x in d.StrappingPlans) sb.Append(string.Join(";", Csv(x.PackageType), x.Stop.ToString(Ci), F(x.HeadPositionMm, "0.#"), Csv(x.Tasks), Csv(x.Strategy))).Append('\n');
        Write(stem + "_piani_legatura.csv", sb.ToString());
        return files;
    }
