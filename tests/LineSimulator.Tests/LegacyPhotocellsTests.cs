using LineSimulator.Core;
using LineSimulator.Engine;
using LineSimulator.Infrastructure;
using LineSimulator.Models;

namespace LineSimulator.Tests;

/// <summary>Revisore, seconda revisione (2026-11-22): B16 (file salvati prima di B15), B17 (accumulo sull'ultima zona), C8 (svincolo ridiviso).</summary>
public class LegacyPhotocellsTests
{
    private static LineProject Release75m(int lengthMm)
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var rel = StrappingAreaRules.ReleaseModules(p).Single();
        double oldEnd = rel.EndMm;
        LineReflow.Fit(rel, rel.StartMm, rel.StartMm + 60 * rel.RollerPitchMm);
        LineReflow.AfterResize(p, rel, oldEnd);
        p.Infeed.TypeSequence = new List<string> { p.PackageTypes.Single(t => Math.Abs(t.LengthMm - lengthMm) < 1).Id };
        p.Infeed.PackageCount = 6;
        return p;
    }

    [Fact]
    public void LegacyProject_ParkingPhotocells_StayAccumulation()
    {
        var p = Release75m(12000);
        _ = new SimulationEngine(p);                                       // divide lo svincolo e crea le FCS…
        var old = ProjectSerializer.Clone(p);
        var fcs = old.Photocells.Where(x => x.Id.StartsWith("FCS", StringComparison.Ordinal)).ToList();
        Assert.NotEmpty(fcs);
        foreach (var x in fcs) x.IsAutoGenerated = false;                  // come in un file salvato prima di B15
        var e = new SimulationEngine(old);
        Assert.All(old.Photocells.Where(x => x.Id.StartsWith("FCS", StringComparison.Ordinal)), x =>
        {
            Assert.Equal(PhotocellAction.Accumulation, x.Action);
            Assert.True(x.IsAutoGenerated);
        });
        Assert.DoesNotContain(e.Preparation.Changes, c => c.StartsWith("FCS", StringComparison.Ordinal) && c.Contains("aggiunta a mano", StringComparison.Ordinal));
        e.RunToCompletion();
        Assert.True(e.CompletedNormally, e.FinishReason);
        Assert.Equal(0, e.Collisions);
    }

    [Fact]
    public void LegacyExample_StopperSlowdown_IsAdopted()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var slow = p.Photocells.Single(x => x.Action == PhotocellAction.SlowDown);
        slow.IsAutoGenerated = false;                                      // FC2 di un vecchio esempio salvato
        PhotocellRules.ApplyProcess(p);
        Assert.Equal(PhotocellAction.SlowDown, slow.Action);
        Assert.True(slow.IsAutoGenerated);
        Assert.Single(p.Photocells, x => x.Action == PhotocellAction.SlowDown);   // nessuna FCR aggiunta accanto
        Assert.Empty(PhotocellRules.ApplyProcess(p));
    }

    [Fact]
    public void AccumulationOnLastZone_UsedInAConsent_StaysAsPresence()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var last = new LineTopology(p).Zones[^1];
        p.Photocells.Add(new PhotocellConfig
        {
            Id = "FCX", Name = "Accumulo", PositionMm = last.StartM * 1000 + 1000, ControlledInverterId = last.Id,
            Action = PhotocellAction.Accumulation, ResponseTimeMs = 20, IsAutoGenerated = true
        });
        p.Rules.Add(new LogicRule { Id = "R1", Action = RuleAction.SetSignal, SignalName = "X", ConditionExpression = "PC(FCX)" });
        var r = SimulationPreparation.Prepare(p);
        var fcx = p.Photocells.Single(x => x.Id == "FCX");
        Assert.Equal(PhotocellAction.None, fcx.Action);
        Assert.False(r.HasErrors, string.Join(" | ", r.Errors));
        Assert.Equal("PC(FCX)", p.Rules.Single().ConditionExpression);
    }

    [Fact]
    public void RemovingOneSectionOfASplitRelease_RedividesFromTheTotalLength()
    {
        var p = Release75m(12000);
        _ = new SimulationEngine(p);
        var secs = StrappingAreaRules.ReleaseModules(p);
        Assert.Equal(5, secs.Count);
        ProjectEditing.Delete(p, new object[] { secs[2] });
        var e = new SimulationEngine(p);
        var now = StrappingAreaRules.ReleaseModules(p);
        Assert.Equal(4, now.Count);
        Assert.All(now, s => Assert.Equal(12, s.RollerCount));
        var parking = p.Photocells.Where(x => x.Id.StartsWith("FCS", StringComparison.Ordinal)).ToList();
        Assert.Equal(3, parking.Count);
        foreach (var pc in parking)
        {
            var s = now.Single(x => x.Id == pc.ControlledInverterId);
            Assert.InRange(pc.PositionMm, s.StartMm, s.EndMm);
        }
        e.RunToCompletion();
        Assert.True(e.CompletedNormally, e.FinishReason);
        Assert.Equal(0, e.Collisions);
    }
}
