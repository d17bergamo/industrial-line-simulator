using System.Text.Json;
using System.Text.RegularExpressions;
using DocumentFormat.OpenXml.Packaging;
using LineSimulator.Core;
using LineSimulator.Infrastructure;
using LineSimulator.Models;

namespace LineSimulator.Tests;

/// <summary>Output dell'ottimizzazione: logica di controllo, specifica funzionale Word, zone di comando.</summary>
public class OutputTests
{
    private static string TempDir()
    {
        var d = Path.Combine(Path.GetTempPath(), "ils-out-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(d);
        return d;
    }

    [Fact]
    public void ControlLogic_RulesAreValidAndOrNotConditions()
    {
        var p = SampleProjects.CreateFullProcessLine();
        var d = ControlLogicGenerator.Generate(p);
        Assert.NotEmpty(d.Rules);
        foreach (var r in d.Rules)
        {
            var c = ConditionText.Parse(r.Condition); // deve essere un'espressione AND/OR/NOT valida
            Assert.NotNull(c);
            foreach (Match m in Regex.Matches(r.Condition, @"PC\(([^)]+)\)"))
                Assert.Contains(p.Photocells, x => x.Id == m.Groups[1].Value);
        }
        Assert.Equal(new LineTopology(p).Zones.Count, d.InverterCount);
        Assert.Equal(d.InverterCount, d.Inverters.Count);

        // Ripartenza comandata dalla fotocellula a monte, arresto dopo la corsa a vuoto
        var m2Start = d.Rules.Single(r => r.Id == "M2.AVVIO");
        Assert.StartsWith("PC(FC1)", m2Start.Condition);
        var m2Stop = d.Rules.Single(r => r.Id == "M2.ARRESTO_VUOTO");
        Assert.Contains("SIG(M2_CORSA_VUOTO)", m2Stop.Condition);
        Assert.Contains("!PC(FC1)", m2Stop.Condition);
        // Interblocco KNOF → legatura
        Assert.Contains("DEV(KNOF,Closed)", d.Rules.Single(r => r.Id == "L1.AVVIO_CICLO").Condition);
        Assert.Contains(d.Rules, r => r.Id == "KNOF.CHIUSURA");
        Assert.Contains(d.Rules, r => r.Id == "L1.CARICA_FILO");
        // Fotocellule: posizione, scopo, regole
        var fct = d.Photocells.Single(x => x.Id.StartsWith("FCT", StringComparison.Ordinal));
        Assert.Contains("trasferitore", fct.Purpose);
        Assert.True(fct.AutoGenerated);
        Assert.NotEmpty(fct.Rules);
        Assert.Contains("Ingresso", d.Photocells.Single(x => x.Id == "FC0").Purpose);
        Assert.Contains("Ripartenza di M2", d.Photocells.Single(x => x.Id == "FC1").Purpose);
        // Piani di legatura per tipologia
        Assert.Contains(d.StrappingPlans, x => x.PackageType == "P12" && x.Tasks.Contains("L1") && x.Tasks.Contains("L3"));
        Assert.Contains(d.StrappingPlans, x => x.PackageType == "P6");
    }

    [Fact]
    public void ControlLogic_ExportsJsonAndCsv()
    {
        var dir = TempDir();
        var d = ControlLogicGenerator.Generate(SampleProjects.CreateStandardLine());
        var files = ControlLogicGenerator.Export(d, Path.Combine(dir, "logica.json"));
        Assert.Equal(6, files.Count);
        Assert.All(files, f => Assert.True(File.Exists(f), f));
        using var json = JsonDocument.Parse(File.ReadAllText(Path.Combine(dir, "logica.json")));
        Assert.True(json.RootElement.GetProperty("rules").GetArrayLength() > 10);
        Assert.StartsWith("ID;Gruppo;Condizione;Azione", File.ReadAllText(Path.Combine(dir, "logica_regole.csv")).TrimStart('﻿'));
    }

    [Fact]
    public void FunctionalSpec_IsWordDocumentWithAllChapters()
    {
        var dir = TempDir();
        string path = Path.Combine(dir, "specifica.docx");
        var p = SampleProjects.CreateFullProcessLine();
        p.Infeed.PackageCount = 2;
        var e = new LineSimulator.Engine.SimulationEngine(p);
        e.RunToCompletion();
        FunctionalSpecExporter.Export(p, e.ComputeResults(), path);
        Assert.True(File.Exists(path));
        using var doc = WordprocessingDocument.Open(path, false);
        var body = doc.MainDocumentPart!.Document.Body!;
        string text = body.InnerText;
        foreach (var chapter in new[] { "Specifica tecnica funzionale", "1. Descrizione del layout e delle macchine", "3. Sequenze di funzionamento",
                                        "4. Regole logiche di controllo", "5. Interblocchi e tempi di default", "6. Risultati di simulazione" })
            Assert.Contains(chapter, text);
        Assert.Contains("P6 (6000 mm): double banking", text);
        Assert.Contains("P12 (12000 mm): single banking", text);
        Assert.Contains("KNOF", text);
        Assert.True(body.Elements<DocumentFormat.OpenXml.Wordprocessing.Table>().Count() >= 6);
    }

    [Fact]
    public void CommandZoneOptimizer_FindsMinimumInvertersAmongValidPartitions()
    {
        var p = SampleProjects.CreateStandardLine();
        var report = CommandZoneOptimizer.Optimize(p, packagesPerType: 2);
        Assert.NotNull(report.Best);
        Assert.True(report.Best!.Valid);
        Assert.True(report.Best.Inverters <= p.Sections.Count);
        // Nessuna suddivisione con meno inverter è ammessa
        Assert.All(report.Candidates.Where(c => c.Inverters < report.Best.Inverters), c => Assert.False(c.Valid));
        Assert.Contains("Criterio", report.Explanation);

        // La suddivisione applicata al progetto è valida e simulabile
        var q = ProjectSerializer.Clone(p);
        CommandZoneOptimizer.Apply(q, report.Best);
        Assert.Equal(report.Best.Inverters, new LineTopology(q).Zones.Count);
        Assert.False(ProjectValidator.Validate(q).HasErrors);

        // Deterministico
        var again = CommandZoneOptimizer.Optimize(p, packagesPerType: 2);
        Assert.Equal(report.Best.Label, again.Best!.Label);
    }
}
