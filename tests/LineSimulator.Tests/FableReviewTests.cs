    /// <summary>Modifiche tipiche dell'utente a un esempio (nome, modifica).</summary>
    private static readonly (string Name, Action<LineProject> Apply)[] Edits =
    {
        ("trasferitore allungato di 2,5 m", p => p.Transfer.LengthMm += 2500),
        ("fermo scomparente aggiunto fuori posto e double banking", p =>
        {
            if (!p.IntermediateStops.Any(s => s.IsEnabled))
                p.IntermediateStops.Add(new IntermediateStopConfig { Id = "FM1", Name = "Fermo scomparente", Placement = DevicePlacement.Center, PositionMm = p.Transfer.PositionMm + 1000, AlignmentTimeS = 2.0 });
            else p.IntermediateStops[0].PositionMm += 1000;
            BankingOptions.SetBankingAll(p, AccumulationMode.DoubleBanking);
        }),
        ("ultima legatrice spostata vicino al trasferitore", p => p.Strappers.OrderBy(s => s.PositionMm).Last().PositionMm = p.Transfer.PositionMm - 500),
        ("prima legatrice spostata a 500 mm dall'inizio", p => p.Strappers.OrderBy(s => s.PositionMm).First().PositionMm = 500),
        ("fotocellule automatiche tolte", p => p.Photocells.RemoveAll(x => x.IsAutoGenerated)),
        ("tipologia più corta tolta", p =>
        {
            var t = p.PackageTypes.OrderBy(x => x.LengthMm).First();
            p.PackageTypes.Remove(t);
            p.Infeed.TypeSequence.RemoveAll(id => id == t.Id);
        }),
        ("via del trasferitore più veloce (1,5 m/s)", p => { var m = LayoutRules.TransferModule(p)!; m.HighSpeed = 1.5; m.MaxSpeed = 1.5; }),
        ("una legatrice disabilitata", p => p.Strappers.OrderBy(s => s.PositionMm).Last().IsEnabled = p.Strappers.Count == 1)
    };

    public static IEnumerable<object[]> Cases() =>
        from m in SampleProjects.All
        from i in Enumerable.Range(0, Edits.Length)
        select new object[] { m.Name, i };

    /// <summary>
    /// Dopo "Sistema automaticamente" non deve restare nulla da correggere (nessuna correzione che ne annulla un'altra o che
    /// serve due volte) e il motore non deve preparare altro: l'elenco mostrato all'utente è tutto ciò che cambia.
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void AutoFix_AfterAUserEdit_IsCompleteInOnePass(string model, int edit)
    {
        var p = SampleProjects.All.Single(m => m.Name == model).Factory();
        Edits[edit].Apply(p);
        var first = ProjectAutoFix.Run(p);
        var second = ProjectAutoFix.Preview(p);
        Assert.True(!second.Changed, $"{Edits[edit].Name}: dopo la correzione resta da correggere:\n{string.Join("\n", second.Messages)}\n--- prima passata:\n{string.Join("\n", first.Messages)}");
        if (first.HasErrors) return;      // modifica non simulabile: l'errore viene mostrato all'utente
        p.Infeed.Continuous = false;
        p.Infeed.PackageCount = Math.Min(p.Infeed.PackageCount, 2 * Math.Max(1, p.Infeed.TypeSequence.Count));
        var e = new SimulationEngine(p);
        Assert.True(!e.Preparation.Changed, $"{Edits[edit].Name}: il motore ha corretto ancora il progetto:\n{string.Join("\n", e.Preparation.Changes)}");
        if (e.Validation.HasErrors) return;
        e.RunToCompletion();
        var bad = e.Events.Where(x => x.Severity >= EventSeverity.Error).Select(x => x.ToString()).Take(8).ToList();
        Assert.True(e.CompletedNormally && e.Collisions == 0, $"{Edits[edit].Name}: {e.FinishReason}\n{string.Join("\n", bad)}");
    }

    /// <summary>
    /// Con la regola di ingresso "un pacco alla volta in legatura" l'intervallo fisso non è usato: non può essere indicato
    /// come collo di bottiglia (prima bastava un intervallo impostato alto, anche se inutilizzato).
    /// </summary>
    [Fact]
    public void Bottleneck_IsNeverTheUnusedFixedInterval()
    {
        var p = SampleProjects.CreateTwoStrappers12m();
        Assert.Equal(InfeedMode.AfterStrapping, p.Infeed.Mode);
        p.Infeed.IntervalS = 1000;
        var e = new SimulationEngine(p);
        e.RunToCompletion();
        Assert.True(e.CompletedNormally, e.FinishReason);
        var r = e.ComputeResults();
        Assert.NotEqual("INFEED", r.BottleneckId);
        Assert.DoesNotContain("intervallo", r.BottleneckExplanation, StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>
    /// Il double banking riportato a single per un pacco troppo lungo viene spiegato con il suo motivo (prima compariva
    /// "Intestatura di coda non disponibile", che non c'entrava).
    /// </summary>
    [Fact]
    public void Preparation_ExplainsWhyDoubleBankingIsResetToSingle()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        BankingOptions.SetBankingAll(p, AccumulationMode.DoubleBanking);
        var longest = p.PackageTypes.OrderBy(t => t.LengthMm).Last();
        Assert.False(BankingOptions.DoubleBankingAvailable(p, longest));
        var r = SimulationPreparation.Prepare(p);
        Assert.Contains(r.Changes, c => c.Contains(longest.Id, StringComparison.Ordinal) && c.Contains("double banking non possibile", StringComparison.Ordinal));
        Assert.DoesNotContain(r.Changes, c => c.Contains("Intestatura di coda non disponibile", StringComparison.Ordinal));
        Assert.Equal(AccumulationMode.SingleBanking, longest.Banking);
    }

    /// <summary>
    /// L'anteprima delle correzioni lavora su una copia identica: se mancano i sensori automatici li elenca, come farà
    /// l'applicazione (prima la copia li aggiungeva in silenzio e l'anteprima diceva "niente da correggere").
    /// </summary>
    [Fact]
    public void AutoFix_Preview_ListsTheSensorsThatRunAdds()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        Assert.True(p.Photocells.RemoveAll(x => x.IsAutoGenerated) > 0);
        int count = p.Photocells.Count;
        var copy = ProjectSerializer.Clone(p);
        Assert.Equal(count, copy.Photocells.Count);
        var preview = ProjectAutoFix.Preview(p);
        Assert.Equal(count, p.Photocells.Count);
        Assert.True(preview.Changed);
        var run = ProjectAutoFix.Run(p);
        Assert.Equal(preview.Messages, run.Messages);
        Assert.True(p.Photocells.Count > count);
    }

