using LineSimulator.Core;
using LineSimulator.Engine;
using LineSimulator.Models;

namespace LineSimulator.Tests;

/// <summary>Fotocellule di processo sempre corrette dal programma (revisore B15, regola dell'utente del 2026-11-22).</summary>
public class ProcessPhotocellsTests
{
    private static LineProject WithAccumulationOnTheLastZone()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var last = new LineTopology(p).Zones[^1];
        p.Photocells.Add(new PhotocellConfig
        {
            Id = "FCX", Name = "Accumulo sull'ultima zona", PositionMm = last.StartM * 1000 + 1000, ControlledInverterId = last.Id,
            Action = PhotocellAction.Accumulation, ResponseTimeMs = 20
        });
        return p;
    }

    [Fact]
    public void AccumulationOnTheLastZone_IsRemovedByThePreparation_AndTheSimulationEnds()
    {
        var p = WithAccumulationOnTheLastZone();
        var e = new SimulationEngine(p);
        Assert.DoesNotContain(p.Photocells, x => x.Id == "FCX");
        Assert.Contains(e.Preparation.Changes, c => c.StartsWith("FCX:", StringComparison.Ordinal) && c.Contains("ultima zona", StringComparison.Ordinal));
        p.Infeed.PackageCount = 3;
        e.RunToCompletion();
        Assert.True(e.CompletedNormally, e.FinishReason);
        Assert.False(e.Deadlocked, e.FinishReason);
    }

    [Fact]
    public void Validator_AccumulationOnLastZone_IsAnError()
    {
        var p = WithAccumulationOnTheLastZone();
        var report = ProjectValidator.Validate(p);
        Assert.Contains(report.Errors, i => i.Code == "PC_ACC_LAST" && i.ComponentId == "FCX");
    }

    [Fact]
    public void AccumulationPhotocell_AlwaysCommandsTheZoneItIsIn()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var zones = new LineTopology(p).Zones;
        var mid = zones[1];
        p.Photocells.Add(new PhotocellConfig
        {
            Id = "FCY", Name = "Accumulo", PositionMm = mid.EndM * 1000 - 500, ControlledInverterId = zones[0].Id,
            Action = PhotocellAction.Accumulation, ResponseTimeMs = 20
        });
        _ = new SimulationEngine(p);
        Assert.Equal(mid.Id, p.Photocells.Single(x => x.Id == "FCY").ControlledInverterId);
    }

    [Fact]
    public void ProcessPhotocells_Idempotent()
    {
        var p = WithAccumulationOnTheLastZone();
        _ = new SimulationEngine(p);
        string once = LineSimulator.Infrastructure.ProjectSerializer.Serialize(p);
        Assert.Empty(PhotocellRules.ApplyProcess(p));
        Assert.Equal(once, LineSimulator.Infrastructure.ProjectSerializer.Serialize(p));
    }

    [Fact]
    public void ParkingPhotocells_AreAutomatic()
    {
        var p = SampleProjects.CreateThreeStrappers24m();
        var rel = StrappingAreaRules.ReleaseModules(p).Single();
        double oldEnd = rel.EndMm;
        LineReflow.Fit(rel, rel.StartMm, rel.StartMm + 60 * rel.RollerPitchMm);
        LineReflow.AfterResize(p, rel, oldEnd);
        _ = new SimulationEngine(p);
        var parking = p.Photocells.Where(x => x.Id.StartsWith("FCS", StringComparison.Ordinal)).ToList();
        Assert.NotEmpty(parking);
        Assert.All(parking, x => Assert.True(x.IsAutoGenerated));
    }
}
